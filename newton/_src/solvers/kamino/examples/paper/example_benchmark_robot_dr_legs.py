    def _init_animation(self, world_count: int) -> None:
        asset_path = newton.utils.download_asset("disneyresearch")
        anim_file = str(asset_path / "dr_legs/animation" / "dr_legs_animation_100fps.npy")
        anim = np.load(anim_file).astype(np.float32)
        if anim.shape[1] != len(_ANIMATION_JOINT_PATHS):
            raise RuntimeError(f"animation has {anim.shape[1]} channels, expected {len(_ANIMATION_JOINT_PATHS)}")
        joint_label = list(self.model.joint_label)
        joint_qd_start = self.model.joint_qd_start.numpy()
        try:
            channel_dofs = np.array(
                [joint_qd_start[joint_label.index(path)] for path in _ANIMATION_JOINT_PATHS],
                dtype=np.int64,
            )
        except ValueError as e:
            raise RuntimeError(f"animation joint not found in model.joint_label: {e}") from e
        n_dof_per_world = self.model.joint_dof_count // world_count
        world_offsets = np.arange(world_count, dtype=np.int64) * n_dof_per_world
        # 2-D fancy-index assignment broadcasts a (12,) RHS across worlds.
        self._animation_indices = channel_dofs[None, :] + world_offsets[:, None]
        self._animation_data = anim * _ANIMATION_CHANNEL_SIGN[None, :]
        self._target_pos_host = self.control.joint_target_pos.numpy()

    def _update_animation_targets(self):
        n_frames = self._animation_data.shape[0]
        frame = min(int(self.sim_time * self._animation_speed / self._animation_dt), n_frames - 1)
        self._target_pos_host[self._animation_indices] = self._animation_data[frame]
        self.control.joint_target_pos.assign(self._target_pos_host)

    def _reset_state(self, state: newton.State):
        wp.copy(state.body_q, self.model.body_q)
        wp.copy(state.body_qd, self.model.body_qd)
        wp.copy(state.joint_q, self.model.joint_q)
        wp.copy(state.joint_qd, self.model.joint_qd)
        if state.body_q_prev is not None:
            wp.copy(state.body_q_prev, state.body_q)
        if state.body_qdd is not None:
            state.body_qdd.zero_()
        if state.body_parent_f is not None:
            state.body_parent_f.zero_()
        if state.joint_parent_f is not None:
            state.joint_parent_f.zero_()
        state.clear_forces()

    def _reset_control(self, control: newton.Control):
        control.clear()
        wp.copy(control.joint_target_pos, self.model.joint_target_pos)
        wp.copy(control.joint_target_vel, self.model.joint_target_vel)
        wp.copy(control.joint_act, self.model.joint_act)

    def _step_setup_standalone(self, setup: SolverSetup):
        for _ in range(self.sim_substeps):
            self.model.collide(self.state_0, self.contacts)
            self.state_0.clear_forces()
            # self.viewer.apply_forces(self.state_0)
            apply_external_force(self.forced_body_index, self.model, self.time, self.state_0, self.sim_dt)
            setup.step(self.state_0, self.control, self.contacts, self.state_1, self.vcontacts)
            self.state_0, self.state_1 = self.state_1, self.state_0

