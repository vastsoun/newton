def eval_kd(ke, epsilon):
    # Approximate restitution coefficient epsilon created by damping ratio zeta
    # is epsilon = exp(- pi * zeta / sqrt(1 - zeta^2))
    # We invert this formula (keeping the positive root) to compute the damping ratio given epsilon
    temp = -np.log(epsilon)
    temp2 = temp * temp
    zeta = np.sqrt(temp2 / (temp2 + np.pi * np.pi))

    # Set kd given ke and the damping ratio zeta = kd / (2 * sqrt(ke))
    return zeta * 2.0 * np.sqrt(ke)


MUJOCO_KE = 6.0e3
MUJOCO_KD = eval_kd(MUJOCO_KE, RESTITUTION)  # Set K_d to emulate target restitution (by under-damping)
MUJOCO_IMPRATIO = 100.0


