class Example:
    def __init__(self, viewer: newton.viewer.ViewerBase, args, use_graph=True, start_paused=False):
        # Set simulation run-time configurations
        self.viewer_fps = 50
        self.viewer_dt = 1.0 / self.viewer_fps
        target_sim_dt = 0.0025  # 400 fps
        self.sim_substeps = max(1, round(self.viewer_dt / target_sim_dt))
        self.sim_dt = self.viewer_dt / self.sim_substeps
        msg.notif(f"Using sim_dt = {self.sim_dt} ({self.sim_substeps} substeps per frame)")
        self.sim_time = 0.0
        self.viewer = viewer
        self.args = args
        self.device = wp.get_device()
        self.use_graph = use_graph
        self.start_paused = start_paused

        # Whether to switch the geometry to a box
        use_box = False

        # Setup trajectory recording
        self.record_traj = False
        self.frame_id = 0
        if self.record_traj:
            self.num_recording_frames = int(np.floor(RECORD_END_TIME / self.viewer_dt)) + 1
            self.traj = np.zeros((self.num_recording_frames, 3))
            self.recording_folder = os.path.join(
                get_examples_output_path(), "bouncing_ball" if not use_box else "bouncing_box"
            )
            os.makedirs(self.recording_folder, exist_ok=True)

        # Clip recording state
        self.record_clips = False
        if getattr(args, "record", None):
            self.video_target_frames = int(np.floor(RECORD_END_TIME / self.viewer_dt)) + 1

        # External forces: applied in viewer vs automatically (currently none)
        self.viewer_forces = True

        # Create the solver setups
        self.setup_kamino = make_setup_solver_kamino(self.sim_dt, 5000, use_box=use_box)
        self.setup_mujoco = make_setup_solver_mujoco(self.sim_dt, 5000, use_box=use_box)
        self.setup_xpbd = make_setup_solver_xpbd(self.sim_dt, 5000, use_box=use_box)

        # Load reference trajectory
        self.use_ref_traj = False
        ref_folder = os.path.join(get_kamino_assets_directory(), "validation", "Reference")
        self.body_q_ref = np.load(os.path.join(ref_folder, "body_q_ref_bouncing_ball.npy"))

        # Solver setup choice
        self.setup_names = ["Kamino", "MuJoCo", "XPBD", "Reference"]
        self.setups = [self.setup_kamino, self.setup_mujoco, self.setup_xpbd, self.setup_kamino]
        self.current_setup_id = 0
        self.init_setup(reset_viewer=True, first=True)

    @property
    def setup(self):
        return self.setups[self.current_setup_id]

    def capture(self):
        self.graph = None
        if self.device.is_cuda:
            with wp.ScopedCapture() as capture:
                self.simulate()
            self.graph = capture.graph

    def reset(self):
        self.frame_id = 0
        self.setup.reset()

    def start_recording_clip(self):
        """Start a new video clip for the currently active solver."""
        if not hasattr(self.viewer, "start_clip"):
            msg.warning("Recording is not enabled (pass --record sync|async at launch).")
            return
        solver_name = self.setup_names[self.current_setup_id]
        self.viewer.start_clip(
            output_path=os.path.join(self.args.video_base_dir, f"recording_{solver_name}.mp4"),
            max_frames=self.video_target_frames,
            video_folder=os.path.join(self.args.video_base_dir, f"frames_{solver_name}"),
            fps=self.viewer_fps,
            keep_frames=self.args.keep_frames,
        )

    def init_setup(self, reset_viewer=True, first=False):
        solver_name = self.setup_names[self.current_setup_id]
        self.use_ref_traj = solver_name == "Reference"
        msg.notif(f"Initializing {solver_name} solver")

        # Reset state
        self.reset()

        # Set model in viewer
        if reset_viewer:
            self.viewer.set_model(self.setup.model)
            self.viewer._paused = self.start_paused  # Start paused to inspect the initial configuration
            if hasattr(self.viewer, "set_camera"):  # Set initial camera on viewer
                camera_pos = wp.vec3(4.0, 0.0, 1.0)
                pitch = -5.0
                yaw = 180.0
                self.viewer.set_camera(camera_pos, pitch, yaw)
            self.viewer.show_contacts = True
            self.viewer.vsync = True
        if reset_viewer and not first and hasattr(self.viewer, "register_ui_callback"):
            # We skip GUI registration on first call as it is done in newton.examples.run() automatically
            self.viewer.register_ui_callback(lambda ui, ex=self: ex.gui(ui), position="side")

        # Reset graph
        self.graph = None

        # Warm-up simulation
        self.setup.step(self.setup.state_0, self.sim_dt)
        self.reset()

        # Capture graph again
        if self.use_graph:
            self.capture()

    # simulate() performs one frame's worth of updates
    def simulate(self):
        for _ in range(self.sim_substeps):
            # Clear and apply forces to the solver state
            self.setup.state_0.clear_forces()
            if self.viewer_forces:
                self.viewer.apply_forces(self.setup.state_0)

            # Step solver
            self.setup.step(self.setup.state_0, self.sim_dt)

            # Swap the leading solver state
            self.setup.state_0, self.setup.state_1 = self.setup.state_1, self.setup.state_0

    def step(self):
        # Optionally record trajectory (before step so we capture the first frame)
        if self.record_traj:
            if self.frame_id < self.num_recording_frames:
                self.traj[self.frame_id] = self.setup.state_0.body_q.numpy()[0, :3]
                if self.frame_id == self.num_recording_frames - 1:
                    solver_name = self.setup_names[self.current_setup_id]
                    np.save(os.path.join(self.recording_folder, f"traj_{solver_name}_{RESTITUTION}.npy"), self.traj)
                    msg.notif("Trajectory recorded")

        # Perform step
        if self.graph:
            wp.capture_launch(self.graph)
        else:
            self.simulate()
        self.sim_time += self.viewer_dt
        self.frame_id += 1

        # Optionally overwrite state with reference solution
        if self.use_ref_traj:
            if self.frame_id < self.body_q_ref.shape[0]:
                self.setup.state_0.body_q.assign(self.body_q_ref[self.frame_id])

    def render(self):
        self.viewer.begin_frame(self.sim_time)
        self.setup.render(self.viewer)
        self.viewer.end_frame()

    @staticmethod
    def create_parser():
        return newton.examples.create_parser()

    def gui(self, imgui):
        # Checkbox to toggle force input (applied in viewer, or automatic force ramp-up)
        clicked, self.viewer_forces = imgui.checkbox("User-applied forces", self.viewer_forces)
        if clicked:
            self.init_setup(reset_viewer=False)

        # Toggle for solver backend
        imgui.text("Solver backend")
        if imgui.begin_combo("##solver_combo", self.setup_names[self.current_setup_id]):
            for solver_id, solver_name in enumerate(self.setup_names):
                selected = solver_id == self.current_setup_id
                clicked, _ = imgui.selectable(solver_name, selected)
                if clicked:
                    self.current_setup_id = solver_id
                    self.init_setup(reset_viewer=True)
                if selected:
                    imgui.set_item_default_focus()
            imgui.end_combo()

        # Checkbox to record a clip on the next Reset press
        if getattr(self.args, "record", None) and hasattr(self.viewer, "start_clip"):
            _, self.record_clips = imgui.checkbox("Record clip on Reset", self.record_clips)

        # Reset button (using the solver-internal reset, rather than fully reloading the example and GUI)
        if imgui.button("Reset##custom_reset"):
            self.reset()
            if self.record_clips and hasattr(self.viewer, "start_clip"):
                self.start_recording_clip()


