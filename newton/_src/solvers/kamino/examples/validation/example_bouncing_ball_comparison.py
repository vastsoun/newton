def build_sphere_on_plane(
    builder: newton.ModelBuilder | None = None,
    radius: float = 0.1,
    mass: float = 1.0,
    z_offset: float = 0.0,
    friction: float | None = None,
    restitution: float | None = None,
    ground: bool = True,
    new_world: bool = True,
    use_custom_shape_cfg: bool = False,
    use_box: bool = False,
) -> newton.ModelBuilder:
    """
    Constructs a basic model of a free-floating 'box' body and a ground box geom.

    Args:
        builder (ModelBuilder | None):
            An optional existing model builder to populate.\n
            If `None`, a new builder is created.
        z_offset (float):
            A vertical offset to apply to the initial position of the box.
        ground (bool):
            Whether to add a static ground plane to the model.
        new_world (bool):
            Whether to begin a new world in the builder for this model.\n
            If `True` (or `builder` is `None`), the model is wrapped in a new world context
            opened via :meth:`ModelBuilder.begin_world` and closed via
            :meth:`ModelBuilder.end_world`.\n
            If `False`, the caller must already be inside an active world; the model is then
            added to that currently active world.

    Returns:
        ModelBuilder: The populated model builder.
    """
    from newton._src.geometry import inertia  # noqa: PLC0415

    # Create a new builder if none is provided
    if builder is None:
        _builder = newton.ModelBuilder()
    else:
        _builder = builder

    # Begin a new world in the builder if requested or if a new builder was created
    if new_world or builder is None:
        _builder.begin_world(label="bouncing_ball")

    # Add the sphere/box body
    r_i: float = radius
    m_i: float = mass
    if not use_box:
        i_I_i = inertia.compute_inertia_sphere_from_mass(mass=m_i, radius=r_i)
    else:
        i_I_i = inertia.compute_inertia_box_from_mass(mass=m_i, hx=r_i, hy=r_i, hz=r_i)
    xform = wp.transformf(0.0, 0.0, r_i + z_offset, 0.0, 0.0, 0.0, 1.0)
    bid0 = _builder.add_body(
        label="sphere" if not use_box else "box",
        mass=m_i,
        inertia=i_I_i,
        xform=xform,
        lock_inertia=True,
    )

    # Use custom shape config if requested
    custom_shape_cfg = (
        newton.ModelBuilder.ShapeConfig(
            gap=0.0,
            margin=0.0,
            mu=friction if friction is not None else _builder.default_shape_cfg.mu,
            restitution=restitution if restitution is not None else _builder.default_shape_cfg.restitution,
        )
        if use_custom_shape_cfg
        else _builder.default_shape_cfg
    )

    # Add collision geometries
    if not use_box:
        _builder.add_shape_sphere(
            label="sphere_geom",
            body=bid0,
            radius=r_i,
            cfg=custom_shape_cfg,
        )
    else:
        _builder.add_shape_box(
            label="sphere_geom",
            body=bid0,
            hx=r_i,
            hy=r_i,
            hz=r_i,
            cfg=custom_shape_cfg,
        )

    # Add a static collision geometry for the plane
    if ground:
        _builder.add_ground_plane(
            cfg=custom_shape_cfg,
            label="ground",
            height=0.0,
        )

    # Close the world context if we opened one
    if new_world or builder is None:
        _builder.end_world()

    # Return the populated model builder
    return _builder


def make_setup_solver_kamino(dt: float, max_frames: int, use_box: bool = False) -> SolverSetup:
    builder = newton.ModelBuilder(up_axis=newton.Axis.Z)
    newton.solvers.SolverKamino.register_custom_attributes(builder)
    builder.request_contact_attributes("force")
    build_sphere_on_plane(
        builder=builder,
        radius=0.1,
        mass=1.0,
        z_offset=START_HEIGHT,
        friction=FRICTION,
        restitution=RESTITUTION,
        ground=True,
        use_custom_shape_cfg=True,
        use_box=use_box,
    )
    model = builder.finalize(skip_validation_joints=True)
    model.rigid_contact_max = 4
    solver_config = newton.solvers.SolverKamino.Config.from_model(model)
    solver_config.padmm.primal_tolerance = 1e-6
    solver_config.padmm.dual_tolerance = 1e-6
    solver_config.padmm.compl_tolerance = 1e-6
    solver_config.padmm.max_iterations = 200
    solver_config.padmm.rho_0 = 1.0
    solver_config.padmm.warmstart_mode = "none"
    solver = newton.solvers.SolverKamino(model=model, config=solver_config)
    # metrics = SolutionMetricsNewton(
    #    dt=dt,
    #    model=model,
    #    sparse=False,
    # )
    # logger = SolutionMetricsLogger(
    #    metrics=metrics,
    #    max_frames=max_frames,
    #    mode=SolutionMetricsLogger.Mode.ROLLING,
    # )
    setup = SolverSetup(
        name="kamino",
        builder=builder,
        model=model,
        solver=solver,
        # metrics=metrics,
        # logger=logger,
    )
    solver.reset(state_out=setup.state_0)
    return setup


def make_setup_solver_mujoco(dt: float, max_frames: int, use_box: bool = False) -> SolverSetup:
    builder = newton.ModelBuilder(up_axis=newton.Axis.Z)
    newton.solvers.SolverMuJoCo.register_custom_attributes(builder)
    builder.default_joint_cfg = newton.ModelBuilder.JointDofConfig(limit_ke=1.0e3, limit_kd=1.0e1, friction=1e-5)
    builder.default_shape_cfg.margin = 0.0
    builder.default_shape_cfg.gap = 0.0
    builder.default_shape_cfg.ke = MUJOCO_KE
    builder.default_shape_cfg.kd = MUJOCO_KD
    builder.default_shape_cfg.mu = 0.75
    builder.default_shape_cfg.mu_rolling = 0.0
    builder.default_shape_cfg.mu_torsional = 0.0
    builder.request_contact_attributes("force")
    build_sphere_on_plane(
        builder=builder,
        radius=0.1,
        mass=1.0,
        z_offset=START_HEIGHT,
        friction=FRICTION,
        restitution=RESTITUTION,
        ground=True,
        use_custom_shape_cfg=False,  # Emulated restitution for MuJoCo will come from the default config above
        use_box=use_box,
    )
    model = builder.finalize()
    solver = newton.solvers.SolverMuJoCo(
        model,
        cone="elliptic",
        impratio=MUJOCO_IMPRATIO,
        iterations=200,
        ls_iterations=100,
        nconmax=46,
        njmax=100,
        use_mujoco_contacts=False,
    )
    # metrics = SolutionMetricsNewton(
    #    dt=dt,
    #    model=model,
    #    sparse=False,
    # )
    # logger = SolutionMetricsLogger(
    #    metrics=metrics,
    #    max_frames=max_frames,
    #    mode=SolutionMetricsLogger.Mode.ROLLING,
    # )
    setup = SolverSetup(
        name="mujoco",
        builder=builder,
        model=model,
        solver=solver,
        # metrics=metrics,
        # logger=logger,
    )
    return setup


